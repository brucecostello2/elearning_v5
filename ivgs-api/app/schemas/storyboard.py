class SceneReorderItem(BaseModel):
    """Single item in a scene reorder request."""

    id: UUID
    scene_index: int = Field(ge=1)


class SceneReorderRequest(BaseModel):
    """
    Schema for POST /api/v1/projects/{id}/scenes/reorder.

    Body: [{id, scene_index}, ...]
    """

    items: List[SceneReorderItem] = Field(min_length=1)

    @field_validator("items")
    @classmethod
    def validate_no_duplicates(cls, items: List[SceneReorderItem]) -> List[SceneReorderItem]:
        indices = [item.scene_index for item in items]
        if len(indices) != len(set(indices)):
            raise ValueError("Duplicate scene_index values are not allowed")
        ids = [item.id for item in items]
        if len(ids) != len(set(ids)):
            raise ValueError("Duplicate scene IDs are not allowed")
        return items
